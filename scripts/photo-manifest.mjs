/* Lists every photo the app will ask for, one line per move per purpose, and
   whether the file exists. Writes assets/exercises/EXPECTED_FILES.md so the
   person supplying photos has the exact spelling, and so a test can assert the
   list is current.

     node scripts/photo-manifest.mjs            # rewrite the manifest
     node scripts/photo-manifest.mjs --check    # exit 1 if it is out of date */
import { readdirSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { DAYS } from "../js/data.js";
import { exercisePhotoUrl } from "../js/util.js";

const DIR = new URL("../assets/exercises/", import.meta.url);
const fileFor = (name, kind) => decodeURIComponent(exercisePhotoUrl(name, kind).replace(/^assets\/exercises\//, ""));

export function expectedPhotos() {
  const seen = new Set(), moves = [];
  Object.values(DAYS).forEach(day => {
    [].concat(...Object.values(day.blocks || {}), day.prepMenu || [], day.recovery || [], day.recoveryHolds || [])
      .forEach(ex => { if (ex && ex.name && !seen.has(ex.name)) { seen.add(ex.name); moves.push(ex.name); } });
  });
  moves.sort((a, b) => a.localeCompare(b));
  return moves.map(name => ({
    name,
    timer: fileFor(name, "Timer"), timerExists: existsSync(new URL(fileFor(name, "Timer"), DIR)),
    demo: fileFor(name, "Demo"), demoExists: existsSync(new URL(fileFor(name, "Demo"), DIR))
  }));
}

export function unmatchedFiles(rows) {
  const wanted = new Set(rows.flatMap(r => [r.timer, r.demo]));
  return readdirSync(DIR).filter(f => /\.png$/i.test(f) && !wanted.has(f)).sort();
}

export function manifestText() {
  const rows = expectedPhotos();
  const orphans = unmatchedFiles(rows);
  const tick = b => (b ? "✅" : "—");
  const missingTimer = rows.filter(r => !r.timerExists).length, missingDemo = rows.filter(r => !r.demoExists).length;
  return [
    "# Exercise photos the app looks for",
    "",
    "Generated by `node scripts/photo-manifest.mjs` from the moves in `js/data.js`. Spelling must match exactly.",
    "Timer images show in the session photo slot (portrait, at least 720×960). Demo images show in the Move",
    "Library and the ⓘ card (any aspect ratio; the app falls back to the Timer image when there is no Demo).",
    "",
    `${rows.length} moves · Timer images missing: ${missingTimer} · Demo images missing: ${missingDemo}`,
    "",
    "| Move | Timer image | Have it | Demo image | Have it |",
    "|---|---|---|---|---|",
    ...rows.map(r => `| ${r.name} | \`${r.timer}\` | ${tick(r.timerExists)} | \`${r.demo}\` | ${tick(r.demoExists)} |`),
    "",
    "## Files in the folder that no move asks for",
    "",
    ...(orphans.length ? orphans.map(f => `- \`${f}\``) : ["- none"]),
    ""
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = new URL("EXPECTED_FILES.md", DIR);
  const text = manifestText();
  if (process.argv.includes("--check")) {
    const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (cur !== text) { console.error("EXPECTED_FILES.md is out of date — run node scripts/photo-manifest.mjs"); process.exit(1); }
    console.log("manifest current");
  } else {
    writeFileSync(out, text);
    console.log("wrote", out.pathname);
  }
}
